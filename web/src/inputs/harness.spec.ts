import { expect, test } from "@playwright/test";

test("farmer inputs work together using explicitly labelled examples", async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  const requests: string[] = [];
  page.on("request", request => { if (request.url().includes("/v1/")) requests.push(request.url()); });
  await page.goto("/src/inputs/harness.html");
  await expect(page.getByText("Example mode", { exact: true })).toBeVisible();
  await expect(page.getByText("40.03", { exact: false }).first()).toBeVisible();
  const picker = page.getByRole("region", { name: "Crop", exact: true });
  await picker.getByRole("combobox").fill("okra");
  await picker.getByRole("option", { name: /Look up “okra”/ }).click();
  await expect(picker.getByRole("status")).toContainText("Checking published references");
  await picker.getByRole("button", { name: "Use Okra" }).click();
  await expect(picker.getByRole("button", { name: "Change crop" })).toBeVisible();
  await expect(picker.getByText("AI suggestion, not verified").first()).toBeVisible();
  const planting = page.getByRole("textbox", { name: "Next planting" });
  await planting.fill("05-12");
  await page.getByRole("button", { name: "Fill typical dates" }).click();
  await expect(planting).toHaveValue("05-12");
  const soybean = page.getByRole("region", { name: "soybean economics" });
  const price = soybean.getByRole("spinbutton", { name: "Price · typical value" });
  await expect(price).toHaveValue("11.2");
  await price.fill("12.5");
  await soybean.getByRole("button", { name: "Reset Price · typical" }).click();
  await expect(price).toHaveValue("11.2");
  await page.getByRole("checkbox", { name: "Sprayer", exact: true }).check();
  await page.getByLabel("Date", { exact: true }).fill("2026-04-15");
  await page.getByRole("button", { name: "Rain I measured" }).click();
  await page.getByRole("spinbutton", { name: "Rainfall (mm)" }).fill("0");
  await page.getByRole("button", { name: "Add reading" }).click();
  await expect(page.getByRole("list", { name: "Recorded readings" }).getByText("Rainfall: 0 mm", { exact: true })).toHaveCount(2);
  await expect(page.getByRole("img", { name: /Rainfall readings by date/ })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: testInfo.outputPath("inputs-desktop.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  expect(requests).toEqual([]);
  await page.reload();
  await expect(page.getByRole("textbox", { name: "Next planting" })).toHaveValue("05-05");
  await expect(page.getByRole("checkbox", { name: "Sprayer", exact: true })).not.toBeChecked();
});
